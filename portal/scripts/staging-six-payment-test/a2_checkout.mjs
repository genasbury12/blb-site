import { signedInPage, site } from "./browser.mjs";
import { load, save, sleep, orderState } from "./lib.mjs";
const s = load();
const { browser, page } = await signedInPage();
await page.goto(`${site}/app/plans`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Six payments of $97" }).click();
await page.waitForURL(/checkout\.stripe\.com/, { timeout: 45000 });
await page.waitForLoadState("networkidle");
const text = (await page.locator("body").innerText()).replace(/\s+/g, " ");
console.log("checkout page:", text.match(/(Sandbox|Test mode|TEST MODE)/i)?.[0] ?? "(no test badge)", "|", text.match(/\$97\.00[^|]{0,40}/)?.[0] ?? "", "| commitment text shown:", /six monthly payments/i.test(text));
await page.setViewportSize({ width: 1280, height: 1600 });
const cardRadio = page.locator('input[type="radio"][value="card"], #payment-method-accordion-item-title-card').first();
if (await cardRadio.count()) await cardRadio.click({ force: true });
else await page.locator("text=Card >> visible=true").first().click();
await page.locator("#cardNumber").waitFor({ state: "visible", timeout: 20000 });
await page.locator("#cardNumber").fill("4242424242424242");
await page.locator("#cardExpiry").fill("12 / 30");
await page.locator("#cardCvc").fill("123");
if (await page.locator("#billingName").count()) await page.locator("#billingName").fill("Staging Test");
if (await page.locator("#billingPostalCode").count()) await page.locator("#billingPostalCode").fill("10001");
const link = page.locator("#enableStripePass"); if (await link.count() && await link.isChecked()) await link.uncheck();
await page.locator('[data-testid="hosted-payment-submit-button"], button.SubmitButton, button[type="submit"]').first().click();
await page.waitForURL(/blb-site-portal\.vercel\.app\/app\/billing/, { timeout: 90000 });
console.log("returned to portal with checkout =", new URL(page.url()).searchParams.get("checkout"));
await browser.close();
for (let i = 0; i < 30; i++) { const st = await orderState(s.userId); if (st.order?.installments_paid >= 1 && st.order?.stripe_subscription_id) break; await sleep(3000); }
const st = await orderState(s.userId);
s.subscriptionId = st.order?.stripe_subscription_id; save(s);
console.log(JSON.stringify({ status: st.order?.status, paid: `${st.order?.installments_paid} of ${st.order?.installments_total}`, subscription: Boolean(st.order?.stripe_subscription_id), payments: st.payments }));
